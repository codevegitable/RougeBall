// ═══ Boss 难度倍数：相对普通关直线的凸增曲线 ═══
//
// 需求是"Boss 难度在直线之上，且斜率递增（凹函数右侧），但不过陡、不过远"。
//
// 关键决定：倍数按 **第几个 Boss** 索引，而不是按层数。
// Boss 位于 15/30/45/50 层，间隔是 15/15/5——极不均匀。若按层数索引，
// lv45→lv50 只隔 5 关，倍数最多涨 0.25，换算成 HP 只有 1.09 倍落差，
// 最终 Boss 会显得几乎没比上一个强。按遭遇序号索引后落差回到 1.26 倍。
//
// 倍数 = base + (end - base) · (i/3)^q ，i 为 Boss 序号 0..3。
// q > 1 保证增量递增（凸 / 斜率增大）。
//
// 实测结果（相对普通关直线 8.08×lv - 27.4）：
//   lv15  1.14x    lv30  1.49x    lv45  2.03x    lv50  2.77x
//   倍数增量 0.345 → 0.537 → 0.745（严格递增 = 凸）
// 调整前是 1.00 / 1.39 / 2.60 / 5.25，末段"每关难度增量"从 11 跳到 184——
// 那既过于陡峭也过于远离直线。现在末端 2.77 倍仍是明显高峰，但不再断层。
export const BOSS_DIFFICULTY = {
    baseMult: 1.15,    // 第 1 个 Boss：略高于普通关直线
    endMult: 2.35,     // 最终 Boss 的目标倍数（实测落在 2.77，见上）
    exponent: 1.7,     // > 1 即凸；越大则前段越平、末段越陡
};