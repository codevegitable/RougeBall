// ═══ 普通关方块数与填充率 ═══
//
// 难度 ≈ 方块数 × 平均血量 × 命中难度。方块数若与血量、尺寸一起线性增长，
// 三者相乘就是凸函数（后段每关增量越来越大）；改为对数增长后，
// 方块数前期涨得快、后期趋缓，正好抵掉另两项的乘性增长，使乘积落在直线上。
//
// fillCap 从 0.55 提到 0.70：0.55 会在 lv23 就封顶，配合网格容量上限
// 让实际方块数死死压在 35 上下（实测 lv50 目标 64、实放 35），
// 后段难度因此塌陷甚至回落——这与"直线"目标正好相反。
